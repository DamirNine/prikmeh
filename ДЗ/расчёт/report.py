def par(text="", bold=False, italic=False, align=None, size=None, indent=True):
    p = doc.add_paragraph()
    if indent and align is None:
        p.paragraph_format.first_line_indent = Cm(1.0)
    if align == "c":
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif align == "j" or (align is None):
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    for i, part in enumerate(text.split("**")):
        r = p.add_run(part); r.bold = bold or (i % 2 == 1); r.italic = italic
        if size:
            r.font.size = Pt(size)
    return p


def formula(text):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text); r.italic = True
    return p


def head(text, lvl=1):
    h = doc.add_heading(text, lvl)
    for r in h.runs:
        r.font.name = "Times New Roman"; r.font.color.rgb = RGBColor(0, 0, 0)
    return h


def pic(path, w=16.0, caption=None):
    doc.add_picture(path, width=Cm(w)); doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    if caption:
        c = doc.add_paragraph(); c.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = c.add_run(caption); r.font.size = Pt(11); r.italic = True


def table(rows, header=True, widths=None):
    t = doc.add_table(rows=len(rows), cols=len(rows[0])); t.style = "Table Grid"; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            c = t.cell(i, j); c.text = str(v)
            for p in c.paragraphs:
                for r in p.runs:
                    r.font.size = Pt(11); r.bold = header and i == 0
            if widths:
                c.width = Cm(widths[j])
    doc.add_paragraph()
    return t


def placeholder(text):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(f"[{text}]"); r.font.color.rgb = RGBColor(0xC0, 0x00, 0x00); r.italic = True


