cnt = [0]
def H(text, lvl=1):
    cnt[0] = 0  # нумерация пунктов заново в каждом шаге
    doc.add_heading(text, lvl)
def P(text, bold=False, italic=False, color=None):
    p = doc.add_paragraph(); r = p.add_run(text); r.bold = bold; r.italic = italic
    if color: r.font.color.rgb = RGBColor(*color)
    return p
def B(text):  # пункт списка, **...** -> жирный
    p = doc.add_paragraph(style="List Bullet")
    parts = text.split("**")
    for i, part in enumerate(parts):
        r = p.add_run(part); r.bold = (i % 2 == 1)
def N(text):
    cnt[0] += 1
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.9); p.paragraph_format.first_line_indent = Cm(-0.6)
    p.paragraph_format.space_after = Pt(2)
    p.add_run(f"{cnt[0]}. ")
    parts = text.split("**")
    for i, part in enumerate(parts):
        r = p.add_run(part); r.bold = (i % 2 == 1)
def IMG(t, caption):
    doc.add_picture(frame(t), width=Cm(15.5))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    c = doc.add_paragraph(); c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = c.add_run(f"Кадр видео {t} — {caption}"); r.italic = True; r.font.size = Pt(10)
def Q(t, text):  # цитата преподавателя
    p = doc.add_paragraph(); r = p.add_run(f"[{t}] «{text}»"); r.italic = True
    r.font.size = Pt(11); r.font.color.rgb = RGBColor(0x44, 0x44, 0x88)

