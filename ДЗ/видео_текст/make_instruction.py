def frame(t):  # "0:05:40" -> путь к кадру (кадр каждые 20 с, нумерация с 1)
    h, m, s = map(int, t.split(":"))
    return os.path.join(FR, f"f_{(h*3600+m*60+s)//20+1:04d}.jpg")

