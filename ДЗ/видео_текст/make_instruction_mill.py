FR = os.path.join(HERE, "кадры_фрезерная")
OUT = os.path.join(os.path.dirname(HERE), "Инструкция_КОМПАС_ЧПУ_фрезерная_(ДЗ-2).docx")

def frame(t):
    h, m, s = map(int, t.split(":"))
    return os.path.join(FR, f"f_{(h*3600+m*60+s)//20+1:04d}.jpg")

doc = Document()
st = doc.styles["Normal"]; st.font.name = "Times New Roman"; st.font.size = Pt(12)
for s in doc.sections:
    s.left_margin = s.right_margin = Cm(2); s.top_margin = s.bottom_margin = Cm(1.8)

cnt = [0]
def H(text, lvl=1):
    cnt[0] = 0; doc.add_heading(text, lvl)
def P(text, italic=False):
    p = doc.add_paragraph(); r = p.add_run(text); r.italic = italic
def _rich(p, text):
    for i, part in enumerate(text.split("**")):
        r = p.add_run(part); r.bold = (i % 2 == 1)
def B(text): _rich(doc.add_paragraph(style="List Bullet"), text)
def N(text):
    cnt[0] += 1
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.9); p.paragraph_format.first_line_indent = Cm(-0.6)
    p.paragraph_format.space_after = Pt(2)
    p.add_run(f"{cnt[0]}. "); _rich(p, text)
def IMG(t, caption):
    doc.add_picture(frame(t), width=Cm(15.5))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    c = doc.add_paragraph(); c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = c.add_run(f"Кадр видео {t} — {caption}"); r.italic = True; r.font.size = Pt(10)
def Q(t, text):
    p = doc.add_paragraph(); r = p.add_run(f"[{t}] «{text}»"); r.italic = True
    r.font.size = Pt(11); r.font.color.rgb = RGBColor(0x44, 0x44, 0x88)

