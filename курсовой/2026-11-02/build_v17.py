def ptext(p):
    return "".join(t.text or "" for t in p.iter(qn("w:t")))


def find_p(prefix):
    for el in body.iterchildren(qn("w:p")):
        if ptext(el).startswith(prefix):
            return el
    raise KeyError("не найден абзац: " + prefix)


def find_tbl(*keys):
    for t in body.iterchildren(qn("w:tbl")):
        tx = ptext(t)
        if all(k in tx for k in keys):
            return t
    raise KeyError("не найдена таблица: " + str(keys))


def insert_after(anchor, items):
    cur = anchor
    for it in items:
        if isinstance(it, IMG):
            p = parse_xml(f'<w:p {nsdecls("w")}><w:pPr><w:keepNext/><w:jc w:val="center"/></w:pPr></w:p>')
            cur.addnext(p)
            Paragraph(p, doc._body).add_run().add_picture(it.path, width=Emu(it.width))
            cur = p
        else:
            cur.addnext(it)
            cur = it
    return cur


def sub_any(el, old, new):
    """заменить фрагмент, даже если он разбит на несколько w:t; форматирование — первого затронутого"""
    ts = list(el.iter(qn("w:t")))
    full = "".join(t.text or "" for t in ts)
    assert full.count(old) == 1, (old, full.count(old))
    i = full.index(old); j = i + len(old)
    pos, first = 0, True
    for t in ts:
        s0, e0 = pos, pos + len(t.text or ""); pos = e0
        if e0 <= i or s0 >= j:
            continue
        txt = t.text or ""
        t.text = txt[:max(0, i - s0)] + (new if first else "") + (txt[j - s0:] if e0 > j else "")
        t.set(qn("xml:space"), "preserve")
        first = False


def set_cell(tc, txt, head=False):
    p = tc.find(qn("w:p"))
    for r in p.findall(qn("w:r")):
        p.remove(r)
    for r in parse_xml(f'<w:p {nsdecls("w")}>{runs_xml(txt, sz=21 if head else 20, b=head)}</w:p>').findall(qn("w:r")):
        p.append(r)


def clone_p(src, text):
    """копия абзаца (стиль, нумерация, шрифт первого прогона) с новым текстом"""
    p = copy.deepcopy(src)
    runs = p.findall(qn("w:r"))
    for r in runs[1:]:
        p.remove(r)
    for t in runs[0].findall(qn("w:t"))[1:]:
        runs[0].remove(t)
    t = runs[0].find(qn("w:t")); t.text = text; t.set(qn("xml:space"), "preserve")
    for va in runs[0].iter(qn("w:vertAlign")):
        va.getparent().remove(va)
    return p


