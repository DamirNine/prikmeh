def cell_xml(txt, w, head=False, left=False, fill=None):
    shd = f'<w:shd w:val="clear" w:color="auto" w:fill="{fill or "D9EAF7"}"/>' if (head or fill) else ""
    jc = "" if left else '<w:jc w:val="center"/>'
    return (f'<w:tc><w:tcPr><w:tcW w:w="{w}" w:type="dxa"/>{shd}<w:vAlign w:val="center"/></w:tcPr>'
            f'<w:p><w:pPr><w:spacing w:before="0" w:after="0" w:line="240" w:lineRule="auto"/>{jc}</w:pPr>'
            f'{runs_xml(txt, sz=21 if head else 20, b=head)}</w:p></w:tc>')

def TABLE(header, rows, widths, fills=None):
    grid = "".join(f'<w:gridCol w:w="{w}"/>' for w in widths)
    x = (f'<w:tbl {nsdecls("w")}><w:tblPr><w:tblStyle w:val="aff0"/><w:tblW w:w="0" w:type="auto"/>'
         '<w:tblCellMar><w:top w:w="60" w:type="dxa"/><w:left w:w="60" w:type="dxa"/><w:bottom w:w="60" w:type="dxa"/>'
         '<w:right w:w="60" w:type="dxa"/></w:tblCellMar><w:tblLook w:val="04A0" w:firstRow="1" w:lastRow="0" '
         'w:firstColumn="1" w:lastColumn="0" w:noHBand="0" w:noVBand="1"/></w:tblPr>'
         f'<w:tblGrid>{grid}</w:tblGrid>')
    x += '<w:tr><w:trPr><w:tblHeader/></w:trPr>' + "".join(cell_xml(h, w, head=True) for h, w in zip(header, widths)) + "</w:tr>"
    for k, r in enumerate(rows):
        f = (fills or {}).get(k)
        x += "<w:tr>" + "".join(cell_xml(c, w, left=(j == 0), fill=f) for j, (c, w) in enumerate(zip(r, widths))) + "</w:tr>"
    return parse_xml(x + "</w:tbl>")

class IMG:
    def __init__(self, path, width):
        self.path, self.width = path, width

# ---------------------------------------------------------------- поиск и вставка
def ptext(p):
    return "".join(t.text or "" for t in p.iter(qn("w:t")))

def find_p(prefix):
    for el in body.iterchildren(qn("w:p")):
        if ptext(el).startswith(prefix):
            return el
    raise KeyError("не найден абзац: " + prefix)

def find_tbl(*keys):
    for t in body.iterchildren(qn("w:tbl")):
        tx = ptext(t)
        if all(k in tx for k in keys):
            return t
    raise KeyError("не найдена таблица: " + str(keys))

def insert_after(anchor, items):
    cur = anchor
    for it in items:
        if isinstance(it, IMG):
            p = parse_xml(f'<w:p {nsdecls("w")}><w:pPr><w:keepNext/><w:jc w:val="center"/></w:pPr></w:p>')
            cur.addnext(p)
            Paragraph(p, doc._body).add_run().add_picture(it.path, width=Emu(it.width))
            cur = p
        else:
            cur.addnext(it)
            cur = it
    return cur

def replace_p(old, items):
    last = insert_after(old, items)
    old.getparent().remove(old)
    return last

def sub_text(el, old, new, count=1):
    """заменить фрагмент внутри одного w:t"""
    for t in el.iter(qn("w:t")):
        if t.text and old in t.text:
            t.text = t.text.replace(old, new, count)
            return
    raise KeyError(f"нет фрагмента '{old}'")

def set_cell(tc, txt, head=False):
    p = tc.find(qn("w:p"))
    for r in p.findall(qn("w:r")):
        p.remove(r)
    for r in parse_xml(f'<w:p {nsdecls("w")}>{runs_xml(txt, sz=21 if head else 20, b=head)}</w:p>').findall(qn("w:r")):
        p.append(r)

def replace_image(caption_prefix, png):
    cap = find_p(caption_prefix)
    pic_p = cap.getprevious()
    blip = next(pic_p.iter("{http://schemas.openxmlformats.org/drawingml/2006/main}blip"))
    rid = blip.get(qn("r:embed"))
    part = doc.part.related_parts[rid]
    part._blob = open(png, "rb").read()
    w, h = Image.open(png).size
    ext = next(pic_p.iter("{http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing}extent"))
    cx = int(ext.get("cx")); cy = int(round(cx * h / w))
    ext.set("cy", str(cy))
    for a_ext in pic_p.iter("{http://schemas.openxmlformats.org/drawingml/2006/main}ext"):
        if a_ext.get("cx"):
            a_ext.set("cx", str(cx)); a_ext.set("cy", str(cy))
    for nv in pic_p.iter("{http://schemas.openxmlformats.org/drawingml/2006/picture}cNvPr"):
        nv.set("name", os.path.basename(png))
    return cap




