# -*- coding: utf-8 -*-
"""Защёлки кожуха УКП.04.001: язычок — часть боковой стенки (консоль прямоугольного сечения), крючок на свободном конце
заходит под выступ-зацеп на стойке. Расчёт по методике консольных защёлок (Bayer MaterialScience, «Snap-Fit Joints for
Plastics»): деформация в корне ε = 1,5·h·y/L², усилие отгиба P = b·h²·E·ε/(6·L), усилие защёлкивания на скосе
W = P·(μ + tg α)/(1 − μ·tg α); при угле удерживающей грани 90° защёлка не снимается рывком — язычок отжимают пальцем (P).
    python snap_calc.py"""
from math import tan, radians

H = 2.0          # толщина язычка = толщина стенки кожуха, мм
B = 10.0         # ширина язычка, мм
L = 28.0         # длина от корня до крючка, мм
Y = 1.5          # отгиб = высота крючка (зацепление), мм
ALPHA = 30.0     # угол заходного скоса крючка к направлению надвигания, °
N_LATCH = 2      # защёлки: левая и правая стенка

# E — модуль (секущий при 1–2 % для пластиков), [ε] — допускаемая деформация при многократном защёлкивании
# (≈ 0,6 от однократной), μ — трение по стали (стойка). Справочные значения, уточнить по паспорту материала
MAT = {"АБС (по модели)": (2100.0, 0.015, 0.40), "PETG (печать)": (2000.0, 0.020, 0.45), "PLA (печать)": (3300.0, 0.010, 0.40)}

eps = 1.5 * H * Y / L ** 2
print(f"Язычок {B:g} × {H:g} × {L:g} мм, отгиб {Y:g} мм, скос {ALPHA:g}°: деформация в корне ε = 1,5·{H:g}·{Y:g}/{L:g}² = {eps * 100:.2f} %")
for name, (E, e_adm, mu) in MAT.items():
    P = B * H ** 2 * E * eps / (6 * L)
    t = tan(radians(ALPHA))
    W = P * (mu + t) / (1 - mu * t)
    sig = E * eps
    print(f"  {name}: σ = E·ε = {sig:.1f} МПа; [ε] = {e_adm * 100:.1f} % — {'запас ' + format(e_adm / eps, '.1f') if eps <= e_adm else 'ПРЕВЫШЕНИЕ'}; "
          f"отгиб P = {P:.2f} Н; защёлкивание одной W = {W:.2f} Н, кожух целиком {N_LATCH * W:.1f} Н ({N_LATCH * W / 9.81:.2f} кгс)")
