            if e0 <= i or s0 >= j:
                continue
            txt = t.text or ""
            t.text = txt[:max(0, i - s0)] + (new if first else "") + (txt[j - s0:] if e0 > j else "")
            t.set(qn("xml:space"), "preserve"); first = False


