def run_xml(text, font="Times New Roman", sz=28, b=False, i=False, va=None):
    rpr = f'<w:rFonts w:ascii="{font}" w:eastAsia="{font}" w:hAnsi="{font}" w:cs="{font}"/>'
    rpr += ("<w:b/>" if b else "") + ("<w:i/>" if i else "") + f'<w:sz w:val="{sz}"/>'
    rpr += f'<w:vertAlign w:val="{va}"/>' if va else ""
    return f'<w:r><w:rPr>{rpr}</w:rPr><w:t xml:space="preserve">{escape(text)}</w:t></w:r>'


def runs_xml(text, **kw):
    out = []
    for part in TOK.split(text):
        if part.startswith("_{"):
            out.append(run_xml(part[2:-1], va="subscript", **kw))
        elif part.startswith("^{"):
            out.append(run_xml(part[2:-1], va="superscript", **kw))
        elif part:
            out.append(run_xml(part, **kw))
    return "".join(out)


def cell_xml(txt, w, head=False, left=False, fill=None):
    shd = f'<w:shd w:val="clear" w:color="auto" w:fill="{fill or "D9EAF7"}"/>' if (head or fill) else ""
    jc = "" if left else '<w:jc w:val="center"/>'
    return (f'<w:tc><w:tcPr><w:tcW w:w="{w}" w:type="dxa"/>{shd}<w:vAlign w:val="center"/></w:tcPr>'
            f'<w:p><w:pPr><w:keepNext/><w:spacing w:before="0" w:after="0" w:line="240" w:lineRule="auto"/>{jc}</w:pPr>'
            f'{runs_xml(txt, sz=21 if head else 20, b=head)}</w:p></w:tc>')


def TABLE(header, rows, widths, fills=None):
    grid = "".join(f'<w:gridCol w:w="{w}"/>' for w in widths)
    x = (f'<w:tbl {nsdecls("w")}><w:tblPr><w:tblStyle w:val="aff0"/><w:tblW w:w="0" w:type="auto"/>'
         '<w:tblCellMar><w:top w:w="60" w:type="dxa"/><w:left w:w="60" w:type="dxa"/><w:bottom w:w="60" w:type="dxa"/>'
         '<w:right w:w="60" w:type="dxa"/></w:tblCellMar><w:tblLook w:val="04A0" w:firstRow="1" w:lastRow="0" '
         'w:firstColumn="1" w:lastColumn="0" w:noHBand="0" w:noVBand="1"/></w:tblPr>'
         f'<w:tblGrid>{grid}</w:tblGrid>')
    x += '<w:tr><w:trPr><w:tblHeader/></w:trPr>' + "".join(cell_xml(h, w, head=True) for h, w in zip(header, widths)) + "</w:tr>"
    for k, r in enumerate(rows):
        f_ = (fills or {}).get(k)
        x += "<w:tr>" + "".join(cell_xml(c, w, left=(j == 0), fill=f_) for j, (c, w) in enumerate(zip(r, widths))) + "</w:tr>"
    return parse_xml(x + "</w:tbl>")


def ptext(el):
    return "".join(t.text or "" for t in el.iter(qn("w:t")))


def find_p(prefix, root=None):
    for el in (root if root is not None else body).iter(qn("w:p")):
        if ptext(el).startswith(prefix):
            return el
    raise KeyError("не найден абзац: " + prefix)


def find_tbl(*keys):
    for t in body.iterchildren(qn("w:tbl")):
        if all(k in ptext(t) for k in keys):
            return t
    raise KeyError("не найдена таблица: " + str(keys))


def sub_any(el, old, new, count=1):
    """заменить фрагмент, даже если он разбит на несколько w:t; форматирование — первого затронутого"""
    ts = list(el.iter(qn("w:t")))
    full = "".join(t.text or "" for t in ts)
    assert full.count(old) == count, (old, full.count(old), full[:80])
    i = full.index(old); j = i + len(old)
    pos, first = 0, True
    for t in ts:
        s0, e0 = pos, pos + len(t.text or ""); pos = e0
        if e0 <= i or s0 >= j:
            continue
        txt = t.text or ""
        t.text = txt[:max(0, i - s0)] + (new if first else "") + (txt[j - s0:] if e0 > j else "")
        t.set(qn("xml:space"), "preserve")
        first = False


def rpr_kw(p):
    """шрифт первого прогона абзаца: размер, полужирный, курсив"""
    r = p.find(".//" + qn("w:r"))
    sz = r.find(".//" + qn("w:sz"))
    return dict(sz=int(sz.get(qn("w:val"))) if sz is not None else 28, b=r.find(".//" + qn("w:b")) is not None,
                i=r.find(".//" + qn("w:i")) is not None)


def set_runs(p, text):
    """текст абзаца целиком с разметкой _{…}/^{…}; свойства абзаца и шрифт первого прогона сохраняются"""
    kw = rpr_kw(p)
    for r in p.findall(qn("w:r")):
        p.remove(r)
    for r in parse_xml(f'<w:p {nsdecls("w")}>{runs_xml(text, **kw)}</w:p>').findall(qn("w:r")):
        p.append(r)
    return p


def clone(src, text):
    return set_runs(copy.deepcopy(src), text)


def set_cell(tc, txt):
    p = tc.find(qn("w:p"))
    kw = rpr_kw(p)
    for r in p.findall(qn("w:r")):
        p.remove(r)
    for r in parse_xml(f'<w:p {nsdecls("w")}>{runs_xml(txt, **kw)}</w:p>').findall(qn("w:r")):
        p.append(r)


def insert_after(anchor, items):
    cur = anchor
    for it in items:
        cur.addnext(it); cur = it
    return cur


