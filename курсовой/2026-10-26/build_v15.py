TOK = re.compile(r"(_\{[^{}]*\}|\^\{[^{}]*\})")


def run_xml(text, font="Times New Roman", sz=28, b=False, i=False, va=None):
    rpr = f'<w:rFonts w:ascii="{font}" w:eastAsia="{font}" w:hAnsi="{font}" w:cs="{font}"/>'
    rpr += "<w:b/>" if b else ""
    rpr += "<w:i/>" if i else ""
    rpr += f'<w:sz w:val="{sz}"/>'
    rpr += f'<w:vertAlign w:val="{va}"/>' if va else ""
    return f'<w:r><w:rPr>{rpr}</w:rPr><w:t xml:space="preserve">{escape(text)}</w:t></w:r>'


def runs_xml(text, **kw):
    out = []
    for part in TOK.split(text):
        if not part:
            continue
        if part.startswith("_{"):
            out.append(run_xml(part[2:-1], va="subscript", **kw))
        elif part.startswith("^{"):
            out.append(run_xml(part[2:-1], va="superscript", **kw))
        else:
            out.append(run_xml(part, **kw))
    return "".join(out)


def P(ppr, text, **kw):
    return parse_xml(f'<w:p {nsdecls("w")}><w:pPr>{ppr}</w:pPr>{runs_xml(text, **kw)}</w:p>')


